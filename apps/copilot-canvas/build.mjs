// Bundles the spec viewer's markdown renderer, stylesheet, step timing and state picking, and the prompt preamble, into vendor/, so the board
// renders spec, plan and tasks exactly the way the extension does. Run: node apps/copilot-canvas/build.mjs

import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const ext = join(here, 'com.github.copilot', 'extensions', 'speckit-companion');
const webview = join(here, '..', 'vscode', 'webview');
const viewerCore = join(here, '..', '..', 'packages', 'viewer', 'src', 'core');
// esbuild writes source paths into the bundle as comments, relative to its working dir: pin it so the output does not depend on where this runs.
const absWorkingDir = join(here, '..', '..');

// The viewer package resolves to its TypeScript source, so no build of it is needed first.
const conditions = ['source'];

await build({
    entryPoints: [join(viewerCore, 'markdown', 'index.ts')],
    bundle: true,
    absWorkingDir,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    conditions,
    outfile: join(ext, 'vendor', 'viewer-markdown.mjs'),
    banner: { js: '// Generated by build.mjs from packages/viewer/src/core/markdown. Do not edit.' },
    logLevel: 'warning',
});

// The prompt preamble VS Code sends with every command (seed record, lifecycle rules). Pure strings, no host imports.
await build({
    entryPoints: [join(webview, '..', 'src', 'ai-providers', 'promptPreamble.ts')],
    bundle: true,
    absWorkingDir,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    conditions,
    outfile: join(ext, 'vendor', 'preamble.mjs'),
    banner: { js: '// Generated by build.mjs from apps/vscode/src/ai-providers/promptPreamble.ts. Do not edit.' },
    logLevel: 'warning',
});

// The step timing the viewer's Overview shows and its duration format, so the board measures and prints phases the same way.
await build({
    stdin: {
        contents: [
            "export { deriveStepHistory, deriveTimingSummary } from './packages/viewer/src/core/stepHistoryDerivation';",
            "export { formatElapsed } from './packages/viewer/src/core/relativeTime';",
        ].join('\n'),
        resolveDir: absWorkingDir,
        loader: 'ts',
    },
    bundle: true,
    absWorkingDir,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    conditions,
    outfile: join(ext, 'vendor', 'step-history.mjs'),
    banner: { js: '// Generated by build.mjs from packages/viewer/src/core/stepHistoryDerivation.ts and packages/viewer/src/core/relativeTime.ts. Do not edit.' },
    logLevel: 'warning',
});

// The one piece of the viewer's click code the board runs in the page: picking a state in a states card.
await build({
    entryPoints: [join(webview, 'src', 'spec-viewer', 'editor', 'statesSelect.ts')],
    bundle: true,
    absWorkingDir,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    conditions,
    outfile: join(ext, 'vendor', 'states-select.mjs'),
    banner: { js: '// Generated by build.mjs from apps/vscode/webview/src/spec-viewer/editor/statesSelect.ts. Do not edit.' },
    logLevel: 'warning',
});

// The viewer package's built, scoped stylesheet and its VS Code theme (`npm run viewer:build` writes them).
await build({
    stdin: {
        contents: "@import './viewer.css';\n@import './themes/vscode.css';\n",
        resolveDir: join(here, '..', '..', 'packages', 'viewer', 'dist', 'styles'),
        loader: 'css',
    },
    bundle: true,
    absWorkingDir,
    outfile: join(ext, 'vendor', 'viewer.css'),
    loader: { '.svg': 'dataurl', '.png': 'dataurl', '.woff2': 'dataurl' },
    banner: { css: '/* Generated by build.mjs from packages/viewer/styles. Do not edit. */' },
    logLevel: 'warning',
});

console.log('built vendor/viewer-markdown.mjs, vendor/preamble.mjs, vendor/step-history.mjs, vendor/states-select.mjs and vendor/viewer.css');
